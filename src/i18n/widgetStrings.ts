/**
 * Renders the iOS home-screen widget's string table (`ios/OpenRungWidget/WidgetStrings.generated.swift`)
 * from the app's locale tables, so the widget's copy is never hand-duplicated in Swift.
 *
 * Deliberately import-free: `scripts/generate-widget-strings.mjs` loads this file straight into
 * Node (type stripping) next to the nine locale tables, and `__tests__/core/widgetStrings.test.ts`
 * re-renders through Jest and fails when the committed Swift file drifts.
 */

/** The subset of `Strings` the widget shows; every value must be a plain string, not a formatter. */
export const WIDGET_STRING_KEYS = [
  'appName',
  'actionConnect',
  'statusDisconnected',
  'statusConnecting',
  'statusConnected',
  'statusDisconnecting',
  'statusFailed',
  'widgetName',
  'widgetDescription',
] as const;

export type WidgetStringKey = (typeof WIDGET_STRING_KEYS)[number];

/** Same order as `SUPPORTED_TAGS` in `src/i18n/index.tsx`; English first, it is the fallback. */
export const WIDGET_TAGS = [
  'en',
  'zh-CN',
  'zh-TW',
  'fa',
  'ru',
  'ar',
  'tr',
  'vi',
  'my',
] as const;

export type WidgetTag = (typeof WIDGET_TAGS)[number];

/** A locale's full table after English fallback (`{ ...en, ...override }`), as `stringsForTag` builds it. */
export type WidgetStringSource = Record<string, unknown>;

export const WIDGET_STRINGS_HEADER =
  '// Generated by scripts/generate-widget-strings.mjs from src/i18n/strings/*.ts — do not edit.\n' +
  '// Regenerate with `npm run widget:strings`; __tests__/core/widgetStrings.test.ts fails on drift.\n';

function swiftLiteral(value: string): string {
  let out = '"';
  for (const char of value) {
    const code = char.codePointAt(0) ?? 0;
    if (char === '\\') {
      out += '\\\\';
    } else if (char === '"') {
      out += '\\"';
    } else if (char === '\n') {
      out += '\\n';
    } else if (char === '\r') {
      out += '\\r';
    } else if (char === '\t') {
      out += '\\t';
    } else if (code < 0x20 || code === 0x7f) {
      out += `\\u{${code.toString(16)}}`;
    } else {
      out += char;
    }
  }
  return out + '"';
}

/**
 * Produces the Swift source for `enum WidgetStringTables`. Throws when a tag is missing or a widget
 * key is absent or not a string in any locale, so a broken table can never be generated.
 */
export function renderWidgetStringsSwift(
  tables: Record<WidgetTag, WidgetStringSource>,
): string {
  const lines: string[] = [WIDGET_STRINGS_HEADER, 'enum WidgetStringTables {'];
  lines.push(
    `    static let tags: [String] = [${WIDGET_TAGS.map(swiftLiteral).join(', ')}]`,
  );
  lines.push(
    `    static let keys: [String] = [${WIDGET_STRING_KEYS.map(swiftLiteral).join(', ')}]`,
  );
  lines.push('    static let tables: [String: [String: String]] = [');
  for (const tag of WIDGET_TAGS) {
    const table = tables[tag];
    if (table == null) {
      throw new Error(`widget strings: no table for "${tag}"`);
    }
    lines.push(`        ${swiftLiteral(tag)}: [`);
    for (const key of WIDGET_STRING_KEYS) {
      const value = table[key];
      if (typeof value !== 'string' || value.length === 0) {
        throw new Error(`widget strings: "${tag}" has no string for "${key}"`);
      }
      lines.push(`            ${swiftLiteral(key)}: ${swiftLiteral(value)},`);
    }
    lines.push('        ],');
  }
  lines.push('    ]', '}', '');
  return lines.join('\n');
}
